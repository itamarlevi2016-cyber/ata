// הרחבה מתקפלת שמופיעה מתחת להוראה. פתיחה וסגירה לא עוצרות את התרגיל.
export function renderGuide(g) {
  if (!g) return null;
  const sec = (title, ...kids) => h("section", { class: "guide-sec" }, h("h4", null, title), ...kids);
  return h(
    "details",
    { class: "step-guide" },
    h("summary", null, h("span", null, "📖 הסבר מפורט: איך עושים את זה"), h("span", { class: "guide-hint" }, "לחצו לפתיחה")),
    h(
      "div",
      { class: "guide-body" },
      g.goal && h("p", { class: "guide-goal" }, h("b", null, "למה עושים את זה? "), g.goal),
      g.how?.length && sec("צעד אחרי צעד", h("ol", { class: "guide-how" }, g.how.map((t) => h("li", null, t)))),
      g.amount && sec("כמה זמן", h("p", null, g.amount)),
      g.feel && sec("מה אמורים להרגיש", h("p", null, g.feel)),
      g.mistakes?.length && sec("טעויות נפוצות", h("ul", { class: "guide-mistakes" }, g.mistakes.map(([m, fix]) => h("li", null, h("b", null, m), " ", fix)))),
      g.easier && sec("אם קשה", h("p", null, g.easier))
    )
  );
}
